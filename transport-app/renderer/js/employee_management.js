addEmployeeForm.addEventListener("submit", async (e) => {
  e.preventDefault();

  const full_name = document.getElementById("empName")?.value?.trim();
  const email = document.getElementById("empEmail")?.value?.trim();
  const phone = document.getElementById("empPhone")?.value?.trim();
  const position = document.getElementById("empPosition")?.value?.trim();
  const department = document.getElementById("empDept")?.value?.trim();
  const status = document.getElementById("empStatus")?.value;
  
  const employee_id = document.getElementById("empEmployeeId")?.value;
  const auth_password = document.getElementById("empTempPassword")?.value;
  const employee_pin4 = document.getElementById("empPin4")?.value;
  
  const daily_rate = parseFloat(document.getElementById("empDailyRate")?.value || "0");
  const salary = parseFloat(document.getElementById("empSalary")?.value || "0");

  // Frontend validation
  if (!full_name) {
    return alert("Name is required.");
  }
  if (!email) {
    return alert("Email is required.");
  }
  const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
  if (!emailRegex.test(email)) {
    return alert("Please enter a valid email address.");
  }
  if (phone && !/^[\d\s\+\-\(\)]{7,20}$/.test(phone)) {
    return alert("Please enter a valid phone number (digits, spaces, +, -, () only, 7-20 chars).");
  }
  if (daily_rate < 0) {
    return alert("Daily rate cannot be negative.");
  }
  if (salary < 0) {
    return alert("Salary cannot be negative.");
  }

  const payload = {
    employee_id,
    full_name,
    email,
    phone: phone || null,
    status: status || "available",
    position: position || "Driver",
    department: department || "Operations",
    auth_email: email,
    auth_password,
    daily_rate,
    salary
  };

  console.log("createEmployee payload:", payload);
  console.log("derived values:", {
    employee_id,
    employee_pin4,
    auth_password,
  });

  try {
    const result = await window.api.createEmployee(payload);

    if (!result?.ok) {
      alert("Failed to add employee: " + (result?.message || "Unknown error"));
      return;
    }

    alert(
      `Employee Created!\nEmployee ID: ${employee_id}\nPIN: ${employee_pin4}\nAuth Password: ${auth_password}`
    );

    addEmployeeModal.style.display = "none";
    addEmployeeForm.reset();
    await setAddModalAutoFields();

    await fetchEmployees();
  } catch (err) {
    console.error(err);
    alert("Error adding employee. Check console.");
  }
});

