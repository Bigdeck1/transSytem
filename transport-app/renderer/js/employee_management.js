// ------------------------------
// EMPLOYEE ID / PIN / AUTH PASSWORD RULES
// employee_id   = EMP0008
// username      = employee_id
// employee_pin4 = generated by DB from last 4 digits of employee_id
// auth_password = EMP + employee_pin4
// ------------------------------
function parseEmpNumber(employeeId) {
  if (!employeeId) return null;
  const s = String(employeeId).trim().toUpperCase();
  if (!s.startsWith("EMP")) return null;
  const n = parseInt(s.slice(3), 10);
  return Number.isFinite(n) ? n : null;
}

function computeNextEmployeeId() {
  const START = 8;
  let max = START - 1;

  for (const emp of cachedEmployees) {
    const n = parseEmpNumber(emp.employee_id);
    if (n !== null && n > max) max = n;
  }

  const next = max + 1;
  return `EMP${String(next).padStart(4, "0")}`;
}

function pinFromEmployeeId(employeeId) {
  return String(employeeId || "").slice(-4);
}

function authPasswordFromPin(pin4) {
  return `EMP${String(pin4 || "").trim()}`;
}

