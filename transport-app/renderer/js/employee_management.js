let allEmployees = [];

async function fetchEmployees() {
  try {
    const [employees, trips, requests] = await Promise.all([
      window.api.getEmployees(),
      window.api.getTrips(),
      window.api.getTimeOffRequests()
    ]);
    
    allEmployees = employees;
    allTrips = trips;
    allTimeOffRequests = requests;
    cachedEmployees = allEmployees; 
    renderEmployees(allEmployees);
  } catch (err) {
    console.error("❌ Error fetching employees:", err);
  }
}

function getDynamicStatus(emp, requests, trips, date = new Date()) {
  let status = emp.status || "available";
  const empRole = (emp.role || emp.position || "").trim().toLowerCase();

  // Time-off checks (highest priority)
  const approvedTimeOff = requests.find(r =>
    String(r.employee_id) === String(emp.id) &&
    r.status.toLowerCase() === "approved" &&
    new Date(r.start_date) <= date &&
    date <= new Date(r.end_date)
  );
  if (approvedTimeOff) return "unavailable";

  const pendingTimeOff = requests.find(r =>
    String(r.employee_id) === String(emp.id) &&
    r.status.toLowerCase() === "pending" &&
    new Date(r.start_date) <= date &&
    date <= new Date(r.end_date)
  );
  if (pendingTimeOff) status = "partially";

  // Trip check (only drivers)
  if (empRole === "driver") {
    const empTrips = trips.filter(t => String(t.driver_id) === String(emp.id));
    for (let t of empTrips) {
      const start = new Date(t.pickup_time);
      const end = new Date(t.delivery_time);
      const tripStatus = (t.status || "").trim().toLowerCase();

      // Currently on a trip => unavailable
      if (start <= date && date <= end && ["in transit", "in-transit"].includes(tripStatus)) {
        return "unavailable";
      }

      // Future or pending trips => busy
      if (["pending", "scheduled", "delayed"].includes(tripStatus) && start >= date) {
        if (status !== "unavailable") status = "busy";
      }
    }
  }
  return status;
}

function renderEmployees(employees) {
  employeeTableBody.innerHTML = "";

  const filterText = searchInput?.value?.trim().toLowerCase() || "";

  if (!filterText) {
    employeeTableBody.innerHTML = `<tr><td colspan="6" style="text-align:center; padding: 40px; color: var(--text-muted);">Please use the search bar to display records.</td></tr>`;
    return;
  }

  const filteredEmployees = employees.filter(emp => {
      const searchableText = `${emp.full_name} ${emp.employee_id} ${emp.id} ${emp.position} ${emp.department} ${emp.email}`.toLowerCase();
      return searchableText.includes(filterText);
  });

  if (filteredEmployees.length === 0) {
    employeeTableBody.innerHTML = `<tr><td colspan="6" style="text-align:center; padding: 40px; color: var(--text-muted);">No employees found.</td></tr>`;
    return;
  }

  filteredEmployees.forEach((emp) => {
    const tr = document.createElement("tr");
    const dynamicStatus = getDynamicStatus(emp, allTimeOffRequests, allTrips);

    tr.innerHTML = `
      <td>
        <div style="display: flex; align-items: center; gap: 12px;">
           <div style="width: 36px; height: 36px; background: #eff6ff; border-radius: 10px; display: flex; align-items: center; justify-content: center; font-weight: 700; color: var(--primary); font-size: 12px;">
              ${escapeHtml(emp.full_name?.split(' ').map(n => n[0]).join('') || '??')}
           </div>
           <div>
              <div style="font-weight: 700; color: var(--text-main);">${escapeHtml(emp.full_name)}</div>
              <div style="font-size: 11px; color: var(--text-light);">ID: ${escapeHtml(emp.employee_id || emp.id)}</div>
           </div>
        </div>
      </td>
      <td>
        <div style="font-size: 13px; color: var(--text-main);">${escapeHtml(emp.email)}</div>
        <div style="font-size: 11px; color: var(--text-muted);">${escapeHtml(emp.phone || 'No phone')}</div>
      </td>
      <td>
        <div style="font-weight: 600; color: var(--text-main);">${escapeHtml(emp.position)}</div>
        <div style="font-size: 11px; color: var(--text-muted);">${escapeHtml(emp.department)}</div>
      </td>
      <td>
        <span class="badge ${getStatusBadgeClass(dynamicStatus)}">${escapeHtml(dynamicStatus)}</span>
      </td>
      <td style="color: var(--text-muted); font-size: 13px;">
        ${emp.hire_date ? new Date(emp.hire_date).toLocaleDateString() : 'N/A'}
      </td>
      <td style="text-align: right;">
        <button onclick="openEditModal('${emp.id}')" style="background: none; border: none; color: var(--primary); cursor: pointer; padding: 4px;"><i data-lucide="edit-3" size="16"></i></button>
        <button onclick="deleteEmployee('${emp.id}')" style="background: none; border: none; color: var(--error); cursor: pointer; padding: 4px;"><i data-lucide="trash-2" size="16"></i></button>
      </td>
    `;
    employeeTableBody.appendChild(tr);
  });

  if (window.lucide) lucide.createIcons();
}

function getStatusBadgeClass(status) {
  switch (status?.toLowerCase()) {
    case 'available': case 'active': return 'badge-success';
    case 'in-use': case 'busy': return 'badge-info';
    case 'unavailable': case 'on leave': return 'badge-error';
    case 'pending': return 'badge-warning';
    default: return 'badge-info';
  }
}

