// ------------------------------
function initCreateAccountForm() {
  const form = document.getElementById("createAccountForm");
  if (!form) return;

  form.addEventListener("submit", async (e) => {
    e.preventDefault();

    const empId = document.getElementById("createAccEmpId")?.value;
    const username = document.getElementById("accUsername")?.value.trim();
    const pin = document.getElementById("accPassword")?.value.trim();

    const statusEl = document.getElementById("createAccountStatus");
    if (statusEl) {
      statusEl.innerText = " Creating account...";
      statusEl.style.color = "#475569";
    }

    if (!empId || !username || !pin) {
      if (statusEl) {
        statusEl.innerText = " Missing employee, username, or PIN.";
        statusEl.style.color = "red";
      }
      return;
    }

    const authPassword = authPasswordFromPin(pin);

    try {
      if (!window.api.createEmployeeAccount) {
        throw new Error("createEmployeeAccount API is not available.");
      }

      const res = await window.api.createEmployeeAccount(empId, username, authPassword);

      if (res?.success) {
        if (statusEl) {
          statusEl.innerText = " Account created & linked!";
          statusEl.style.color = "green";
        }
        await fetchEmployees();
      } else {
        if (statusEl) {
          statusEl.innerText = " " + (res?.error || "Failed to create account.");
          statusEl.style.color = "red";
        }
      }
    } catch (err) {
      console.error(err);
      if (statusEl) {
        statusEl.innerText = " Error creating account. Check console.";
        statusEl.style.color = "red";
      }
    }
  });
}

