function initSyncButton() {
  const syncBtn = document.getElementById("syncAccountBtn");
  if (!syncBtn) return;

  syncBtn.addEventListener("click", async (e) => {
    e.preventDefault();

    const empId = document.getElementById("editEmpId")?.value;
    const email = document.getElementById("editEmpEmail")?.value;
    const statusEl = document.getElementById("syncStatus");

    if (!empId || !email) {
      if (statusEl) {
        statusEl.innerText = " Missing employee or email.";
        statusEl.style.color = "red";
      }
      return;
    }

    if (statusEl) {
      statusEl.innerText = " Checking existing account...";
      statusEl.style.color = "#475569";
    }

    try {
      if (!window.api.syncEmployeeAccountByEmail) {
        throw new Error("syncEmployeeAccountByEmail API is not available.");
      }

      const result = await window.api.syncEmployeeAccountByEmail(empId, email);

      if (result?.success) {
        if (statusEl) {
          statusEl.innerText = " Account synced successfully!";
          statusEl.style.color = "green";
        }
        await fetchEmployees();
      } else {
        if (statusEl) {
          statusEl.innerText = " " + (result?.error || "Sync failed.");
          statusEl.style.color = "red";
        }
      }
    } catch (err) {
      console.error(err);
      if (statusEl) {
        statusEl.innerText = " Sync failed. Check console.";
        statusEl.style.color = "red";
      }
    }
  });
}